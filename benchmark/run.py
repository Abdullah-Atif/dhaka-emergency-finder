"""Dhaka benchmark: geocoding quality and "nearest on the map vs. fastest to reach".

Run from the repository root (needs GEOAPIFY_API_KEY, about 15 credits per location):
    python benchmark/run.py

Writes benchmark/results.json and benchmark/results.md.
"""

import csv
import json
import os
import sys
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from dhaka_emergency.finder import Origin, find_candidates, rank_by_travel_time  # noqa: E402
from dhaka_emergency.geoapify import GeoapifyClient, GeoapifyError  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))


def area_text(hit):
    keys = ("name", "formatted", "quarter", "suburb", "district", "city", "address_line1", "address_line2")
    return " ".join(str(hit.get(k, "")) for k in keys)


def run_one(client, row):
    out = {"id": int(row["id"]), "query": row["query"], "language": row["language"],
           "expected_area": row["expected_area"]}
    hit = client.geocode(row["query"])
    if not hit:
        out.update(geocoded=None, area_match=False)
        return out
    text = area_text(hit).lower()
    rank = hit.get("rank") or {}
    out.update(
        geocoded=hit.get("formatted", ""),
        result_type=hit.get("result_type", ""),
        match_type=rank.get("match_type", ""),
        confidence=rank.get("confidence"),
        lat=hit["lat"], lon=hit["lon"],
        area_match=any(k.lower() in text for k in row["expected_area"].split("|")),
        coarse=rank.get("match_type", "").startswith(("match_by_city", "match_by_country")),
    )
    if out["coarse"]:
        return out  # the CLI warns here; hospitals around the city centre say nothing useful
    origin = Origin(lon=hit["lon"], lat=hit["lat"], label=hit.get("formatted", ""))
    ranked = rank_by_travel_time(client, origin, find_candidates(client, origin, "hospital"))
    reachable = [f for f in ranked if f.drive_s is not None]
    out["candidates"] = len(ranked)
    if not reachable:
        return out
    fastest = reachable[0]
    nearest = min(reachable, key=lambda f: f.straight_m)
    out.update(
        fastest={"name": fastest.name, "min": round(fastest.drive_s / 60, 1),
                 "road_km": round(fastest.drive_m / 1000, 2), "straight_km": round(fastest.straight_m / 1000, 2),
                 "maybe_not_er": fastest.maybe_not_er},
        map_nearest={"name": nearest.name, "min": round(nearest.drive_s / 60, 1),
                     "road_km": round(nearest.drive_m / 1000, 2), "straight_km": round(nearest.straight_m / 1000, 2)},
        nearest_is_fastest=nearest is fastest,
        minutes_saved=round((nearest.drive_s - fastest.drive_s) / 60, 1),
        detour_ratio=round(fastest.drive_m / max(fastest.straight_m, 1), 2),
    )
    return out


def to_markdown(results):
    n = len(results)
    geo_ok = [r for r in results if r.get("area_match")]
    bn = [r for r in results if r["language"] == "bn"]
    bn_ok = [r for r in bn if r.get("area_match")]
    coarse = [r for r in results if r.get("coarse")]
    missing = [r for r in results if not r.get("geocoded") and "error" not in r]
    ranked = [r for r in results if "fastest" in r]
    differ = [r for r in ranked if not r["nearest_is_fastest"]]
    saved = [r["minutes_saved"] for r in differ]
    not_er = [r for r in ranked if r["fastest"]["maybe_not_er"]]
    lines = [
        f"# Dhaka benchmark results ({date.today().isoformat()})",
        "",
        "Generated by `python benchmark/run.py` against the live Geoapify APIs. "
        "Travel times use `mode=drive`, `traffic=approximated` (an estimate, not live traffic).",
        "",
        "## Summary",
        "",
        f"- **Geocoding landed in the expected area:** {len(geo_ok)} / {n} "
        f"(Bangla-script queries: {len(bn_ok)} / {len(bn)})",
        f"- **Silent fallback to the whole city** (`match_type` = `match_by_city_or_disrict`): {len(coarse)} / {n}"
        + (f": {', '.join(r['query'] for r in coarse)}" if coarse else ""),
        f"- **Not found at all:** {len(missing)} / {n}" + (f": {', '.join(r['query'] for r in missing)}" if missing else ""),
        f"- **The nearest hospital on the map was NOT the fastest to reach:** {len(differ)} / {len(ranked)} locations "
        "(city-level fallbacks excluded)",
    ]
    if saved:
        big = [s for s in saved if s >= 1]
        lines.append(f"  - of these, the fastest one saves **at least 1 minute** in {len(big)} / {len(ranked)}")
        lines.append(f"- **When they differ, the fastest one saves** {min(saved)} to {max(saved)} min "
                     f"(average {sum(saved) / len(saved):.1f} min) by car")
    lines.append(f"- **The fastest \"hospital\" is likely not an emergency hospital** (diagnostic centre, pharmacy, "
                 f"eye hospital, ... by name): {len(not_er)} / {len(ranked)}")
    lines += [
        "",
        "The area check is automatic: the geocoded address must contain one of the expected area names "
        "from `locations.csv`. Every mismatch is reviewed by hand in [NOTES.md](NOTES.md).",
        "",
        "## Geocoding",
        "",
        "| # | Query | Lang | Geocoded to | Type | Expected area? |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        ok = "yes" if r.get("area_match") else "**no**"
        if r.get("coarse"):
            ok += " (city-level only)"
        lines.append(f"| {r['id']} | {r['query']} | {r['language']} | {r.get('geocoded') or '(not found)'} "
                     f"| {r.get('result_type', '')} | {ok} |")
    lines += [
        "",
        "## Nearest on the map vs. fastest to reach (hospitals)",
        "",
        "| # | Query | Fastest to reach | Nearest on the map | Same? | Minutes saved |",
        "|---|---|---|---|---|---|",
    ]
    for r in ranked:
        f, m = r["fastest"], r["map_nearest"]
        same = "yes" if r["nearest_is_fastest"] else "**no**"
        flag = " ⚠ not ER?" if f["maybe_not_er"] else ""
        lines.append(f"| {r['id']} | {r['query']} | {f['name']}{flag} ({f['min']} min, {f['road_km']} km) "
                     f"| {m['name']} ({m['min']} min, {m['straight_km']} km straight) | {same} "
                     f"| {r['minutes_saved'] if not r['nearest_is_fastest'] else '-'} |")
    return "\n".join(lines) + "\n"


def main():
    client = GeoapifyClient()
    with open(os.path.join(HERE, "locations.csv"), encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    results = []
    for row in rows:
        try:
            r = run_one(client, row)
        except GeoapifyError as e:
            r = {"id": int(row["id"]), "query": row["query"], "language": row["language"], "error": str(e)}
        results.append(r)
        status = "ok" if r.get("area_match") else "CHECK"
        print(f"{r['id']:>2}. {status:5} {row['query']} -> {r.get('geocoded') or r.get('error')}", flush=True)
    with open(os.path.join(HERE, "results.json"), "w", encoding="utf-8") as fh:
        json.dump(results, fh, ensure_ascii=False, indent=2)
    with open(os.path.join(HERE, "results.md"), "w", encoding="utf-8") as fh:
        fh.write(to_markdown(results))
    print("\nWrote benchmark/results.json and benchmark/results.md")


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    main()
