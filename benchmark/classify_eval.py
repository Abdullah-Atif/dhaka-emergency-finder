"""Evaluate the facility classifier on every hospital-tagged place in Dhaka city.

Run from the repository root (needs GEOAPIFY_API_KEY, 1 Places request):
    python benchmark/classify_eval.py

Writes benchmark/classify_eval.md: how the 400+ "hospitals" in the map data are classified, how the classifier compares
with OSM's emergency=yes/no tags, and a random sample for manual review (seeded, so it is reproducible for the
same map data).
"""

import collections
import json
import os
import random
import sys
import urllib.parse
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from dhaka_emergency.classify import classify  # noqa: E402
from dhaka_emergency.geoapify import GeoapifyClient  # noqa: E402

DHAKA_RECT = "rect:90.33,23.68,90.47,23.90"   # Dhaka city, Keraniganj edge to Uttara
LABELS = {"confirmed": "24h emergency confirmed by a source", "yes": "government hospital, emergency expected",
          "likely": "hospital, emergency not verified", "specialised": "specialised (one kind of emergency)",
          "unknown": "unknown", "no": "not an emergency facility"}


def fetch(client):
    q = urllib.parse.urlencode({"categories": "healthcare.hospital", "filter": DHAKA_RECT, "limit": 500}, safe=",:")
    feats = client._request("https://api.geoapify.com/v2/places?" + q).get("features", [])
    out = []
    for f in feats:
        p = f["properties"]
        raw = (p.get("datasource") or {}).get("raw") or {}
        out.append({"name": p.get("name"), "nameEn": raw.get("name:en"), "nameBn": raw.get("name:bn"),
                    "tags": {k: v for k, v in raw.items() if k in ("emergency", "healthcare", "healthcare:speciality",
                                                                 "operator:type", "opening_hours")}})
    return out


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    places = fetch(GeoapifyClient())
    for p in places:
        p["c"] = classify(p)
    n = len(places)
    by_ed = collections.Counter(p["c"]["ed"] for p in places)
    no_types = collections.Counter(p["c"]["type"] for p in places if p["c"]["ed"] == "no")
    specs = collections.Counter(p["c"]["speciality"] for p in places if p["c"]["ed"] == "specialised")
    tagged = [p for p in places if p["tags"].get("emergency") in ("yes", "no")]

    lines = [f"# Facility classifier on Dhaka's map data ({date.today().isoformat()})", "",
             f"Generated by `python benchmark/classify_eval.py`: all {n} places that Geoapify returns as "
             "`healthcare.hospital` inside Dhaka city (`" + DHAKA_RECT + "`), classified by name and OSM tags with "
             "[`facility_rules.json`](../docs/app/facility_rules.json).", "",
             "## How the map's \"hospitals\" are classified", "", "| Class | Places | Share |", "|---|---|---|"]
    for ed in ("confirmed", "yes", "likely", "specialised", "unknown", "no"):
        lines.append(f"| {LABELS[ed]} | {by_ed.get(ed, 0)} | {100 * by_ed.get(ed, 0) / n:.0f}% |")
    lines += ["", "**What the \"not an emergency facility\" places really are:** " +
              ", ".join(f"{t} {c}" for t, c in no_types.most_common()), "",
              "**Specialised:** " + ", ".join(f"{s} {c}" for s, c in specs.most_common()), "",
              "## Against OSM's own `emergency=yes/no` tags", "",
              f"{len(tagged)} places carry an emergency tag. Where the classifier and the tag disagree:", "",
              "| Name | OSM tag | Classifier | Why |", "|---|---|---|---|"]
    for p in tagged:
        c = p["c"]
        agree = (p["tags"]["emergency"] == "no" and c["ed"] == "no") or \
                (p["tags"]["emergency"] == "yes" and c["ed"] in ("confirmed", "yes", "likely", "specialised"))
        if not agree:
            lines.append(f"| {p['name'] or '(unnamed)'} | emergency={p['tags']['emergency']} | {c['ed']} ({c['type']}) "
                         f"| {c['reasons'][0] if c['reasons'] else ''} |")
    rnd = random.Random(42)
    sample = rnd.sample([p for p in places if p["name"]], min(40, n))
    lines += ["", "## Random sample for manual review (seed 42)", "",
              "| # | Name | Classifier | Reason |", "|---|---|---|---|"]
    for i, p in enumerate(sample, 1):
        c = p["c"]
        lines.append(f"| {i} | {p['name']} | {c['ed']}{' / ' + c['speciality'] if c['speciality'] else ''} "
                     f"| {c['reasons'][0] if c['reasons'] else ''} |")
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "classify_eval.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{n} places:", dict(by_ed))
    print("Wrote", out)


if __name__ == "__main__":
    main()
